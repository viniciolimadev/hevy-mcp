// Generates docs/tools.md from the tool schemas exposed by the server.
// Usage: npm run build && npm run docs:tools
import { writeFileSync } from "node:fs";
import { Client } from "@modelcontextprotocol/sdk/client/index.js";
import { StdioClientTransport } from "@modelcontextprotocol/sdk/client/stdio.js";

const transport = new StdioClientTransport({
  command: "node",
  args: ["dist/index.js"],
  env: { ...process.env, HEVY_API_KEY: "docs-generation" },
});
const client = new Client({ name: "docs-generator", version: "1.0.0" });
await client.connect(transport);
const { tools } = await client.listTools();
await client.close();

const typeOf = (s) => {
  if (!s) return "any";
  if (s.enum) return s.enum.map((v) => `\`${v}\``).join(" \\| ");
  if (s.anyOf) return [...new Set(s.anyOf.map(typeOf))].filter((t) => t !== "null").join(" \\| ");
  if (s.type === "array") return `${typeOf(s.items)}[]`;
  if (Array.isArray(s.type)) return s.type.filter((t) => t !== "null").join(" \\| ");
  return s.type ?? "any";
};

const constraints = (s) => {
  const c = [];
  const safe = (n) => Math.abs(n) >= Number.MAX_SAFE_INTEGER;
  if (s.minimum !== undefined && !safe(s.minimum)) c.push(`min ${s.minimum}`);
  if (s.maximum !== undefined && !safe(s.maximum)) c.push(`max ${s.maximum}`);
  if (s.minItems !== undefined) c.push(`min ${s.minItems} items`);
  if (s.pattern) c.push(`pattern \`${s.pattern}\``);
  if (s.default !== undefined) c.push(`default \`${JSON.stringify(s.default)}\``);
  return c.join(", ");
};

// Flattens nested objects/arrays into dotted rows: workout.exercises[].sets[].reps
function rows(schema, prefix = "", required = schema.required ?? []) {
  const out = [];
  for (const [name, raw] of Object.entries(schema.properties ?? {})) {
    const s = raw.anyOf?.find((x) => x.type !== "null") ?? raw;
    const path = prefix + name;
    const isObj = s.type === "object" && s.properties;
    const isObjArr = s.type === "array" && s.items?.type === "object";
    out.push({
      path,
      type: isObj ? "object" : isObjArr ? "object[]" : typeOf(raw),
      required: required.includes(name) && raw.default === undefined,
      notes: [raw.description ?? s.description, constraints(s)].filter(Boolean).join(" — "),
    });
    if (isObj) out.push(...rows(s, `${path}.`));
    if (isObjArr) out.push(...rows(s.items, `${path}[].`));
  }
  return out;
}

const badge = (a = {}) => (a.readOnlyHint ? "🔍 read-only" : a.destructiveHint ? "⚠️ overwrites data" : "✏️ write");

let md = `# Tool reference\n\n> Auto-generated by \`npm run docs:tools\` — do not edit by hand.\n\n`;
md += `| Tool | Kind | Description |\n|---|---|---|\n`;
for (const t of tools) md += `| [\`${t.name}\`](#${t.name}) | ${badge(t.annotations)} | ${t.description} |\n`;

for (const t of tools) {
  md += `\n---\n\n## ${t.name}\n\n${badge(t.annotations)} · ${t.description}\n\n`;
  const r = rows(t.inputSchema);
  if (!r.length) {
    md += `_No parameters._\n`;
    continue;
  }
  md += `| Parameter | Type | Required | Notes |\n|---|---|---|---|\n`;
  for (const x of r) md += `| \`${x.path}\` | ${x.type} | ${x.required ? "✅" : ""} | ${x.notes} |\n`;
}

writeFileSync("docs/tools.md", md);
console.log(`docs/tools.md: ${tools.length} tools`);
